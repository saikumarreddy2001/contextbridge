export function storiesForProject(projectId: string): CatchUpStory[] {
  return catchUpStories.filter((story) => story.projectId === projectId)
}

export function guidedStoriesForProject(projectId: string): CatchUpStory[] {
  return storiesForProject(projectId).filter((story) => story.guided)
}

export function storyBySlug(projectId: string, slug: string): CatchUpStory | undefined {
  return storiesForProject(projectId).find((story) => story.slug === slug)
}

export function storyMatchesFilter(story: CatchUpStory, filter: CatchUpFilter): boolean {
  return filter === "all" || story.type === filter
}
